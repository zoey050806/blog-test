/**
 * Main JavaScript for the blog frontend.
 * Handles Markdown rendering, comment interactions, and UI enhancements.
 */
(function () {
    'use strict';

    // ===== Markdown Rendering =====
    function renderMarkdown() {
        var converter = new showdown.Converter({
            tables: true,
            strikethrough: true,
            tasklists: true,
            simpleLineBreaks: false,
            ghCodeBlocks: true,
            emoji: true,
            openLinksInNewWindow: false,
            backslashEscapesHTMLTags: true
        });

        var elements = document.querySelectorAll('.markdown-body[data-markdown]');
        elements.forEach(function (el) {
            var raw = el.getAttribute('data-markdown');
            if (raw) {
                el.innerHTML = converter.makeHtml(raw);
            }
        });

        // Apply syntax highlighting to code blocks
        if (typeof hljs !== 'undefined') {
            document.querySelectorAll('.markdown-body pre code').forEach(function (block) {
                hljs.highlightElement(block);
            });
        }
    }

    // ===== Slug Auto-Generation (for admin form) =====
    function setupSlugGeneration() {
        var titleInput = document.getElementById('title');
        var slugInput = document.getElementById('slug');

        if (titleInput && slugInput) {
            titleInput.addEventListener('input', function () {
                // Only auto-fill slug if it's empty or was previously auto-generated
                if (!slugInput.value || slugInput.dataset.autoGenerated === 'true') {
                    slugInput.value = generateSlug(titleInput.value);
                    slugInput.dataset.autoGenerated = 'true';
                }
            });

            slugInput.addEventListener('input', function () {
                slugInput.dataset.autoGenerated = 'false';
            });
        }
    }

    function generateSlug(text) {
        return text.trim().toLowerCase()
            .replace(/[^\w一-龥]+/g, '-')
            .replace(/^-+|-+$/g, '')
            .replace(/-+/g, '-');
    }

    // ===== Cover Image Upload (admin form) =====
    function setupImageUpload() {
        var coverFile = document.getElementById('coverFile');
        var coverImageField = document.querySelector('input[name="coverImage"]');
        var progressDiv = document.getElementById('uploadProgress');

        if (coverFile && coverImageField) {
            coverFile.addEventListener('change', function () {
                var file = this.files[0];
                if (!file) return;

                var formData = new FormData();
                formData.append('file', file);

                if (progressDiv) {
                    progressDiv.classList.remove('d-none');
                }

                fetch('/admin/posts/upload-image', {
                    method: 'POST',
                    body: formData
                })
                .then(function (response) { return response.json(); })
                .then(function (data) {
                    if (progressDiv) {
                        progressDiv.classList.add('d-none');
                    }
                    if (data.filename) {
                        coverImageField.value = data.filename;
                        // Show preview
                        var preview = document.createElement('img');
                        preview.src = data.url;
                        preview.className = 'img-thumbnail mt-2';
                        preview.style.maxHeight = '150px';
                        var existing = coverImageField.parentNode.querySelector('img');
                        if (existing) existing.remove();
                        coverImageField.parentNode.insertBefore(preview, coverFile);
                    } else if (data.error) {
                        alert('Upload failed: ' + data.error);
                    }
                })
                .catch(function (err) {
                    if (progressDiv) progressDiv.classList.add('d-none');
                    alert('Upload failed. Please try again.');
                    console.error(err);
                });
            });
        }
    }

    // ===== Delete Confirmation =====
    function setupDeleteConfirmations() {
        document.querySelectorAll('[data-confirm]').forEach(function (el) {
            el.addEventListener('click', function (e) {
                if (!confirm(el.dataset.confirm || 'Are you sure?')) {
                    e.preventDefault();
                }
            });
        });
    }

    // ===== Auto-dismiss Alerts =====
    function setupAutoDismiss() {
        document.querySelectorAll('.alert-dismissible').forEach(function (alert) {
            setTimeout(function () {
                var bsAlert = bootstrap.Alert.getInstance(alert);
                if (bsAlert) bsAlert.close();
            }, 5000);
        });
    }

    // ===== Initialize on DOM Ready =====
    document.addEventListener('DOMContentLoaded', function () {
        renderMarkdown();
        setupSlugGeneration();
        setupImageUpload();
        setupDeleteConfirmations();
        setupAutoDismiss();
    });
})();
